class VersionMatchingTests(unittest.TestCase):
    def setUp(self):
        self.cfg = load_config()
        self.track = Track("0" * 22, "Summer Jam - Radio Edit", ("The Underdog Project",), 214, "Album")
        self.audio = dict(id="A" * 11, title="Summer Jam (Radio Edit)",
                          channel="The Underdog Project - Topic", channel_id="UC" + "a" * 22,
                          duration=214, categories=["Music"], album="Album", track="Summer Jam (Radio Edit)",
                          artists=["The Underdog Project"], details_checked=True,
                          description="Provided to YouTube by label\nAuto-generated by YouTube.")
        self.clip = dict(id="B" * 11, title="The Underdog Project - Summer Jam (Radio Edit) (Official Video)",
                         channel="The Underdog Project", channel_is_verified=True, channel_id="UC" + "b" * 22,
                         duration=214, categories=["Music"], details_checked=True)
        self.compare = Mock()
        self.compare.compare.return_value = {"verdict": "match", "windows": [{"similarity": .98}] * 3}

    def choose(self, candidates):
        return resolve(self.track, self.cfg, candidates, self.compare)[0]

    def test_exact_version_clip_available(self):
        self.assertEqual(self.choose([self.audio, self.clip]).candidate["id"], self.clip["id"])
        self.compare.compare.assert_called_once()

    def test_most_viewed_fallback_names_the_song_and_artist(self):
        track = Track("1" * 22, "Love Generation - Edit", ("Bob Sinclar", "Gary Pine"), 204, "")
        ranking = [{"candidate": c} for c in (
            dict(id="A" * 11, title="Bob Sinclar - World Hold On", channel="Bob Sinclar", view_count=900),
            dict(id="B" * 11, title="Bob Sinclar - Love Generation (Official Video)", channel="Embassy One", view_count=200),
            dict(id="C" * 11, title="Love Generation (Edit)", channel="Bob Sinclar", view_count=5),
            dict(id="D" * 11, title="Love Generation cover", channel="Someone", view_count=500),
            dict(id="E" * 11, title="Bob Sinclar - Love Generation", channel="Bob Sinclar", view_count=10 ** 9,
                 live_status="is_upcoming"))]
        chosen = most_viewed(track, ranking)
        self.assertEqual((chosen.candidate["id"], chosen.candidate["fallback"], chosen.accepted), ("B" * 11, True, True))
        # Always a video: another song of the artist rather than nothing.
        self.assertEqual(most_viewed(track, ranking[:1]).candidate["id"], "A" * 11)
        self.assertIsNone(most_viewed(track, [{"reason": "no candidate"}]))

    def test_no_clip_uses_official_audio(self):
        self.assertEqual(self.choose([self.audio]).candidate["id"], self.audio["id"])
        self.compare.compare.assert_not_called()

    def test_disabled_audio_playback_does_not_disable_reference_comparison(self):
        self.cfg["allow_audio_fallback"] = False
        self.assertEqual(self.choose([self.audio, self.clip]).candidate["id"], self.clip["id"])
        self.compare.compare.assert_called_once()

    def test_popular_remix_never_replaces_radio_edit(self):
        for name in ["Alle Farben Remix", "Jerome Remix", "DJ Frank Summermix Short", "Extended Mix", "Live", "Acoustic", "Slowed"]:
            wrong = {**self.clip, "title": f"The Underdog Project - Summer Jam ({name}) (Official Video)", "view_count": 10**10}
            with self.subTest(name=name):
                self.assertFalse(score(self.track, wrong, self.cfg).eligible)
                self.assertEqual(self.choose([wrong, self.audio]).candidate["id"], self.audio["id"])

    def test_almost_identical_named_remixes_stay_distinct(self):
        self.track = Track(self.track.id, "Summer Jam - Alle Farben Remix", self.track.artists, 214)
        for name in ["Alle Farben Club Remix", "Alle Farbe Remix", "Alle Farben Radio Remix", "Other Remix"]:
            candidate = {**self.clip, "title": f"The Underdog Project - Summer Jam ({name}) (Official Video)"}
            self.assertFalse(score(self.track, candidate, self.cfg).eligible)
        exact = {**self.clip, "title": "The Underdog Project - Summer Jam (Alle Farben Remix) (Official Video)"}
        self.assertTrue(score(self.track, exact, self.cfg).accepted)

    def test_missing_version_requires_real_audio_before_clip(self):
        clip = {**self.clip, "title": "The Underdog Project - Summer Jam (Official Video)"}
        self.assertFalse(score(self.track, clip, self.cfg).accepted)
        self.assertEqual(self.choose([clip, self.audio]).candidate["id"], clip["id"])
        self.compare.compare.assert_called_once()

    def test_wrong_audio_in_apparently_official_clip_falls_back(self):
        self.compare.compare.return_value = {"verdict": "mismatch", "windows": [{"similarity": .2}] * 3}
        self.assertEqual(self.choose([self.clip, self.audio]).candidate["id"], self.audio["id"])

    def test_uncertain_clip_blocks_all_sending(self):
        self.compare.compare.return_value = {"verdict": "uncertain", "windows": []}
        with self.assertRaises(AmbiguousMatch):
            self.choose([self.clip, self.audio])

    def test_ambiguous_references_must_be_compared_and_abstain_if_different(self):
        other = {**self.audio, "id": "C" * 11, "view_count": 10**10}
        self.compare.compare.return_value = {"verdict": "mismatch"}
        with self.assertRaisesRegex(AmbiguousMatch, "contradictory") as caught:
            self.choose([self.audio, other])
        self.compare.compare.assert_called_once()
        self.assertEqual(len(caught.exception.ranking), 2)

    def test_audio_failure_is_not_no_match(self):
        self.compare.compare.side_effect = RuntimeError("network")
        with self.assertRaisesRegex(AmbiguousMatch, "network"):
            self.choose([self.audio, self.clip])

    def test_official_audio_beats_unofficial_video(self):
        clip = {**self.clip, "channel_is_verified": False, "view_count": 10**10}
        self.assertEqual(self.choose([clip, self.audio]).candidate["id"], self.audio["id"])

    def test_unofficial_fallback_requires_independent_audio_agreement(self):
        one = {**self.clip, "channel": "Fan One", "channel_is_verified": False}
        two = {**one, "id": "C" * 11, "channel": "Fan Two", "channel_id": "UC" + "c" * 22}
        selected = self.choose([one, two])
        self.assertEqual(selected.tier, 3)
        self.assertEqual(selected.candidate["audio_check"]["verdict"], "match")
        with self.assertRaisesRegex(AmbiguousMatch, "Isolated"):
            self.choose([one])
        with self.assertRaisesRegex(AmbiguousMatch, "Isolated"):
            self.choose([one, {**one, "id": "D" * 11}])

    def test_search_overall_deadline_stops_further_requests(self):
        with patch("youtube_match.time.monotonic", return_value=50), patch("youtube_match.run") as run:
            with self.assertRaisesRegex(RuntimeError, "deadline"):
                search(self.track, self.cfg, deadline=49)
            run.assert_not_called()

    def test_wrong_artist_in_detailed_metadata_rejected(self):
        for changes in ({"artists": ["Another Artist"]}, {"track": "Another Song"}, {"track": "Summer Jam (Jerome Remix)"}):
            with self.subTest(changes=changes):
                self.assertFalse(score(self.track, {**self.audio, **changes}, self.cfg).eligible)

    def test_wrong_album_is_not_silently_trusted(self):
        wrong = {**self.audio, "album": "Different Album"}
        self.assertFalse(score(self.track, wrong, self.cfg).accepted)
        with self.assertRaisesRegex(AmbiguousMatch, "Album conflict"):
            self.choose([wrong])
        good = {**self.audio, "id": "C" * 11}
        self.assertIsNotNone(self.choose([good, wrong]))
        self.compare.compare.assert_called_once()

    def test_compilation_album_requires_two_matching_official_releases(self):
        other = {**self.audio, "id": "C" * 11, "album": "Original release"}
        original = {**self.audio, "album": "Original release"}
        self.assertIsNotNone(self.choose([other, original]))
        self.compare.compare.assert_called_once()

    def test_audio_visualizer_and_official_lyrics_are_valid_fallbacks(self):
        for marker in ["Official Audio", "Visualizer", "Official Lyric Video"]:
            c = {**self.clip, "title": f"The Underdog Project - Summer Jam (Radio Edit) ({marker})"}
            with self.subTest(marker=marker):
                m = score(self.track, c, self.cfg)
                self.assertTrue(m.accepted, m.reasons)
                self.assertEqual((m.tier, m.kind), (2, "audio"))

    def test_topic_name_alone_is_not_official_evidence(self):
        self.assertEqual(score(self.track, {**self.audio, "description": "Fake"}, self.cfg).tier, 3)

    def test_generic_verified_label_no_track_whitelist(self):
        candidate = {**self.clip, "channel": "New Music Label"}
        self.assertEqual(score(self.track, candidate, self.cfg).tier, 1)
        self.assertEqual(score(self.track, {**candidate, "categories": ["Gaming"]}, self.cfg).tier, 3)
        credited = {**candidate, "categories": ["Entertainment"],
                    "description": "The Underdog Project. Directed by A Director."}
        self.assertEqual(score(self.track, credited, self.cfg).tier, 1)

    def test_album_conflict_does_not_promote_unofficial_reference_over_official(self):
        official = {**self.audio, "album": "Original release"}
        other = {**self.clip, "channel_is_verified": False}
        selected = self.choose([other, official])
        self.assertEqual(selected.candidate["id"], official["id"])
        self.assertEqual(self.compare.compare.call_args.args[0]["id"], official["id"])

    def test_corroborated_album_reissue_does_not_accept_wrong_unofficial_audio(self):
        official = {**self.audio, "album": "Original release"}
        other = {**self.clip, "channel_is_verified": False}
        self.compare.compare.return_value = {"verdict": "mismatch"}
        with self.assertRaises(AmbiguousMatch):
            self.choose([other, official])

    def test_portuguese_artist_alias_and_named_collaborators(self):
        cases = [(Track(self.track.id, "Os Muleke É Liso", ("MC Rodolfinho",), 232),
                  "MC Rodolfinho - Os mlk é Liso (Videoclipe Oficial)", "MC Rodolfinho"),
                 (Track(self.track.id, "EARFQUAKE", ("Tyler, The Creator",), 200),
                  "Tyler, The Creator - EARFQUAKE (Official Video)", "Tyler, The Creator"),
                 (Track(self.track.id, "Hate Me (with Juice WRLD)", ("Ellie Goulding", "Juice WRLD"), 186),
                  "Ellie Goulding, Juice WRLD - Hate Me (Official Video)", "Ellie Goulding"),
                 (Track(self.track.id, "Bye Bye", ("Marshmello", "Juice WRLD"), 108),
                  "Juice WRLD & Marshmello - Bye Bye (Official Video)", "Marshmello"),
                 (Track(self.track.id, "Halo", ("Beyoncé",), 240),
                  "Beyonce - Halo (Official Video)", "Beyonce")]
        for track, title, channel in cases:
            c = {**self.clip, "title": title, "channel": channel, "duration": track.duration}
            with self.subTest(title=title):
                m = score(track, c, self.cfg)
                self.assertTrue(m.accepted, m.reasons)

    def test_two_official_clips_with_close_scores_are_compared(self):
        other = {**self.clip, "id": "C" * 11, "view_count": 10**10}
        self.compare.compare.return_value = {"verdict": "mismatch"}
        with self.assertRaises(AmbiguousMatch):
            self.choose([self.clip, other])
        self.compare.compare.assert_called_once()

    def test_tv_collaborators_are_reconciled_with_separate_music_metadata(self):
        track = Track(self.track.id, "Bye Bye", ("Marshmello, Juice WRLD",), 108)
        candidate = {**self.clip, "title": "Marshmello, Juice WRLD - Bye Bye (Official Audio)",
                     "channel": "Marshmello", "artists": ["Marshmello", "Juice WRLD"], "duration": 108}
        m = score(track, candidate, self.cfg)
        self.assertTrue(m.accepted, m.reasons)
        candidate["channel"] = "Juice WRLD"
        m = score(track, candidate, self.cfg)
        self.assertEqual(m.tier, 2)

    def test_verified_music_artist_channel_aggregation(self):
        flat = {**self.clip, "channel_id": "UC" + "z" * 22}
        with patch("youtube_match.run", return_value=json.dumps(self.clip)):
            self.assertEqual(video_details(flat, 10)["channel_id"], self.clip["channel_id"])
        with patch("youtube_match.run", return_value=json.dumps({**self.clip, "channel": "Other Artist"})):
            with self.assertRaises(RuntimeError):
                video_details(flat, 10)

    def test_duration_and_missing_metadata_guards(self):
        for duration in [None, 0, -1, float("nan"), 500]:
            self.assertFalse(score(self.track, {**self.clip, "duration": duration}, self.cfg).eligible)
        self.assertFalse(score(self.track, {**self.clip, "details_checked": False}, self.cfg).accepted)

    def test_reviewed_id_cannot_override_edition(self):
        candidate = {**self.clip, "title": "The Underdog Project - Summer Jam (Other Remix) (Official Video)",
                     "reviewed_track_id": self.track.id}
        self.assertFalse(score(self.track, candidate, self.cfg).eligible)

    def test_version_parser_preserves_named_edit_remaster_and_live_venue(self):
        for title, expected in [("Song - Dance Movement Radio Edit", "dance movement radio edit"),
                                ("Song (Live at Wembley)", "live at wembley"),
                                ("Song - 2011 Remastered", "2011 remaster"),
                                ("Song (Acoustic Version)", "acoustic version")]:
            self.assertEqual(identity(title), ("song", (expected,)))
        self.assertEqual(identity("Radio Edit"), ("radio edit", ()))
        self.assertEqual(identity("With Or Without You"), ("with or without you", ()))

    def test_details_are_fetched_and_network_fields_cannot_inject_evidence(self):
        flat = {k: self.audio[k] for k in ["id", "title", "channel", "channel_id", "duration"]}
        with patch("youtube_match.video_details", return_value=self.audio) as fetch:
            self.assertIsNotNone(self.choose([flat]))
        fetch.assert_called_once()
        with patch("youtube_match.run", return_value=json.dumps({**self.audio, "audio_check": {"verdict": "match"}})):
            self.assertNotIn("audio_check", video_details(flat, 10))
        with patch("youtube_match.run", return_value=json.dumps({**self.audio, "channel_id": "wrong"})):
            with self.assertRaises(RuntimeError):
                video_details(flat, 10)

    def test_topic_search_artist_channel_alias_is_reconciled(self):
        flat = {**self.audio, "channel_id": "UC" + "z" * 22}
        with patch("youtube_match.run", return_value=json.dumps(self.audio)):
            self.assertEqual(video_details(flat, 10)["channel_id"], self.audio["channel_id"])
        fake = {**self.audio, "channel": "Other Artist - Topic"}
        with patch("youtube_match.run", return_value=json.dumps(fake)):
            with self.assertRaises(RuntimeError):
                video_details(flat, 10)


class ActualAudioTests(unittest.TestCase):
    def setUp(self):
        # A deterministic changing spectrum, not a mocked comparison verdict.
        rng = np.random.default_rng(47)
        self.reference = rng.normal(size=(4000, 48)).astype(np.float32)

    def test_same_recording_with_offset_gain_and_noise(self):
        rng = np.random.default_rng(49)
        candidate = np.vstack([rng.normal(size=(150, 48)), self.reference * 1.2 + rng.normal(0, .04, self.reference.shape)])
        result = compare_features(self.reference, candidate)
        self.assertEqual(result["verdict"], "match", result)
        self.assertTrue(all(abs(w["offset"] - 2.4) < .02 for w in result["windows"]))

    def test_different_recording_and_remix_with_shared_intro(self):
        rng = np.random.default_rng(50)
        other = rng.normal(size=self.reference.shape)
        for candidate in [other, np.vstack([self.reference[:1800], other[1800:]])]:
            self.assertEqual(compare_features(self.reference, candidate)["verdict"], "mismatch")

    def test_changed_edit_causes_offset_drift_not_match(self):
        candidate = np.vstack([self.reference[:1700], np.zeros((200, 48)), self.reference[1700:]])
        self.assertNotEqual(compare_features(self.reference, candidate)["verdict"], "match")

    def test_pcm_feature_extraction_checks_silence_and_short_audio(self):
        for pcm in [np.zeros(16000 * 35), np.ones(100), np.full(16000 * 35, np.nan)]:
            with self.assertRaises(RuntimeError):
                features(pcm)

    def test_audio_process_timeout_and_temporary_cleanup(self):
        from pathlib import Path
        with self.assertRaises(subprocess.TimeoutExpired):
            bounded_process([sys.executable, "-c", "import time;time.sleep(30)"], .05)
        with self.assertRaises(RuntimeError):
            with AudioComparator(load_config()) as audio:
                directory = Path(audio.temp.name)
                (directory / "sample").write_bytes(b"audio")
                raise RuntimeError("stop")
        self.assertFalse(directory.exists())


if __name__ == "__main__":
    unittest.main()
